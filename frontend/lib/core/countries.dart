final Map<String, Country> _byIso = {for (final c in kCountries) c.iso: c};

/// Country for an ISO code ("pk" → Pakistan), or null when unknown.
Country? countryByIso(Object? iso) => _byIso['${iso ?? ''}'.trim().toUpperCase()];

/// "Pakistan" for "PK"; the code itself when the country is not in the list.
String countryName(Object? iso) {
  final code = '${iso ?? ''}'.trim().toUpperCase();
  return _byIso[code]?.name ?? code;
}

/// Best first guess for the selector from a browser locale ("en-PK" → PK).
Country? countryFromLocale(String? locale) {
  final m = RegExp(r'[-_]([A-Za-z]{2})\b').firstMatch(locale ?? '');
  return m == null ? null : countryByIso(m.group(1));
}

/// "+92 331 6694449" style display for a stored E.164 number: the dial code
/// is split off; the rest is shown as stored. Anything else is returned as is.
String prettyPhone(Object? phone, Object? iso) {
  final p = '${phone ?? ''}'.trim();
  final c = countryByIso(iso);
  if (c == null || !p.startsWith('+${c.dial}')) return p;
  return '+${c.dial} ${p.substring(c.dial.length + 1)}';
}
